"""Requirements traceability: maps docs/requirements.md rows to tests carrying @pytest.mark.req."""

import argparse
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REQUIREMENTS = ROOT / "docs" / "requirements.md"
JUNIT = ROOT / "docs" / "evidence" / "junit.xml"
OUTPUT = ROOT / "docs" / "evidence" / "traceability.md"

ROW = re.compile(r"^\|\s*([A-Z]+-\d+)\s*\|\s*(\d+)\s*\|\s*(.*)\s*\|\s*([^|]*?)\s*\|\s*$")


def parse_requirements(text: str) -> dict[str, dict]:
    reqs: dict[str, dict] = {}
    for line in text.splitlines():
        m = ROW.match(line)
        if m:
            rid, phase, title, acceptance = m.groups()
            reqs[rid] = {
                "phase": int(phase),
                "title": title.strip(),
                "manual": acceptance.strip().startswith("MANUAL:"),
            }
    return reqs


class _Collector:
    def __init__(self) -> None:
        self.mapping: dict[str, list[str]] = {}

    def pytest_collection_modifyitems(self, items) -> None:  # noqa: ANN001
        for item in items:
            for marker in item.iter_markers("req"):
                for rid in marker.args:
                    self.mapping.setdefault(rid, []).append(item.nodeid)


def collect_markers() -> dict[str, list[str]]:
    import pytest

    collector = _Collector()
    pytest.main(
        ["--collect-only", "-q", "-m", "not live", "-p", "no:cacheprovider"], plugins=[collector]
    )
    return collector.mapping


def junit_outcomes(path: Path) -> dict[str, str]:
    """Map 'file::test' style ids (best effort) to passed/failed from a JUnit report."""
    if not path.exists():
        return {}
    outcomes: dict[str, str] = {}
    root = ET.parse(path).getroot()  # noqa: S314 - junit.xml is generated locally by pytest
    for case in root.iter("testcase"):
        classname = case.get("classname", "").replace(".", "/")
        # classname is dotted module path (+ class); rebuild a suffix-matchable key
        key = f"{classname}::{case.get('name')}"
        failed = case.find("failure") is not None or case.find("error") is not None
        outcomes[key] = "failed" if failed else "passed"
    return outcomes


def _status(nodeids: list[str], outcomes: dict[str, str]) -> str:
    if not outcomes:
        return "collected"
    results = []
    for nodeid in nodeids:
        file_part, _, name = nodeid.partition("::")
        key = f"{file_part.removesuffix('.py')}::{name.split('::')[-1]}"
        results.append(outcomes.get(key))
    if any(r == "failed" for r in results):
        return "failed"
    if all(r == "passed" for r in results):
        return "passed"
    return "collected"


def build_report(reqs: dict, mapping: dict, phase: int, outcomes: dict) -> tuple[str, list[str]]:
    errors = [
        f"unknown requirement id in marker: {rid}" for rid in sorted(mapping) if rid not in reqs
    ]
    lines = [
        "# Traceability matrix",
        "",
        f"Requirements up to phase {phase}. Generated by `tools/traceability.py`.",
        "",
        "| ID | Phase | Requirement | Tests | Status |",
        "|---|---|---|---|---|",
    ]
    for rid, info in reqs.items():
        if info["phase"] > phase:
            continue
        tests = mapping.get(rid, [])
        if info["manual"]:
            status = "manual"
        elif not tests:
            status = "MISSING"
            errors.append(f"{rid}: no test with @pytest.mark.req('{rid}')")
        else:
            status = _status(tests, outcomes)
        cell = "<br>".join(f"`{t}`" for t in tests) or "-"
        title = info["title"].replace("|", "\|")
        lines.append(f"| {rid} | {info['phase']} | {title} | {cell} | {status} |")
    return "\n".join(lines) + "\n", errors


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--phase", type=int, required=True)
    args = parser.parse_args()
    reqs = parse_requirements(REQUIREMENTS.read_text(encoding="utf-8"))
    report, errors = build_report(reqs, collect_markers(), args.phase, junit_outcomes(JUNIT))
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(report, encoding="utf-8")
    for err in errors:
        print(f"TRACEABILITY ERROR: {err}", file=sys.stderr)
    return 1 if errors else 0


if __name__ == "__main__":
    sys.path.insert(0, str(ROOT))
    raise SystemExit(main())
